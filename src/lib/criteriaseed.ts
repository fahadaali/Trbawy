// علامة كل تحميل تُحفظ في settings.criteria_seed (قائمة مفصولة بفواصل). تغيير علامة فئة
// (مثل students-v2) يعيد تحميل قائمتها مرةً جديدة فوق قالبها القائم — فلا تُغيَّر إلا مع
// نسخة معتمدة جديدة من معاييرها.
const SEEDS: Array<{ targetType: string; mark: string; rows: Row[] }> = [
  { targetType: 'students', mark: 'students-v1', rows: STUDENT_CRITERIA },
  { targetType: 'team_members', mark: 'team_members-v1', rows: SUPERVISOR_CRITERIA },
  { targetType: 'first_supervisors', mark: 'first_supervisors-v1', rows: SUPERVISOR_CRITERIA },
];

const hasMark = (marks: string | null, mark: string) => (marks || '').split(',').includes(mark);

/**
 * استبدال قالب كل فئة بقائمتها المعتمدة — مرةً واحدة لكل فئة في كل قاعدة.
 * عبارات الفئة في دفعة واحدة (معاملة) ومشروطة بغياب علامتها، والعلامة تُكتب في آخرها:
 * فإما أن يقع الاستبدال كاملًا مع علامته وإما ألّا يقع شيء، ولو تزامن إقلاع عدّة نسخ.
 * لا يمسّ معايير الدورات المفتوحة أو المغلقة: تلك نسخٌ مثبَّتة داخل كل دورة.
 */
export async function applyApprovedCriteria(env: Env): Promise<void> {
  for (const { targetType, mark, rows } of SEEDS) {
    try {
      // بلا صف إعدادات لا تُحفظ العلامة، فيتكرر الاستبدال مع كل إقلاع ويطمس التعديلات
      const s = await env.DB.prepare('SELECT criteria_seed FROM settings WHERE id = 1').first<{ criteria_seed: string | null }>();
      if (!s || hasMark(s.criteria_seed, mark)) continue;

      const pending = `NOT EXISTS (SELECT 1 FROM settings WHERE id = 1
        AND instr(',' || COALESCE(criteria_seed, '') || ',', ',${mark},') > 0)`;
      await env.DB.batch([
        env.DB.prepare(`DELETE FROM eval_criteria WHERE cycle_id IS NULL AND target_type = ? AND ${pending}`).bind(targetType),
        ...rows.map(([name, description, weight], i) =>
          env.DB.prepare(
            `INSERT INTO eval_criteria (cycle_id, target_type, name, description, weight, sort_order, is_active)
             SELECT NULL, ?, ?, ?, ?, ?, 1 WHERE ${pending}`,
          ).bind(targetType, name, description, weight, i)),
        env.DB.prepare(
          `UPDATE settings SET criteria_seed = COALESCE(criteria_seed || ',', '') || ? WHERE id = 1 AND ${pending}`,
        ).bind(mark),
      ]);
    } catch (e) {
      console.error(`approved criteria seed failed (${targetType})`, e);
    }
  }
}

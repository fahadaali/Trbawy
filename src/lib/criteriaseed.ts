// علامة التحميل في صف الإعدادات. تغييرها (مثل students-v2) يعيد تحميل القائمة أعلاه
// مرةً جديدة فوق قالب الطلاب القائم — فلا تُغيَّر إلا مع نسخة معتمدة جديدة من المعايير.
const SEED_MARK = 'students-v1';

/**
 * استبدال قالب معايير الطلاب بالقائمة المعتمدة — مرةً واحدة لكل قاعدة.
 * العبارات كلها في دفعة واحدة (معاملة) ومشروطة بغياب العلامة، والعلامة تُكتب في آخرها:
 * فإما أن يقع الاستبدال كاملًا مع علامته وإما ألّا يقع شيء، ولو تزامن إقلاع عدّة نسخ.
 * لا يمسّ معايير الدورات المفتوحة أو المغلقة: تلك نسخٌ مثبَّتة داخل كل دورة.
 */
export async function applyStudentCriteria(env: Env): Promise<void> {
  try {
    // بلا صف إعدادات لا تُحفظ العلامة، فيتكرر الاستبدال مع كل إقلاع ويطمس التعديلات
    const s = await env.DB.prepare('SELECT criteria_seed FROM settings WHERE id = 1').first<{ criteria_seed: string | null }>();
    if (!s || s.criteria_seed === SEED_MARK) return;

    const pending = `NOT EXISTS (SELECT 1 FROM settings WHERE id = 1 AND criteria_seed = '${SEED_MARK}')`;
    await env.DB.batch([
      env.DB.prepare(`DELETE FROM eval_criteria WHERE cycle_id IS NULL AND target_type = 'students' AND ${pending}`),
      ...STUDENT_CRITERIA.map(([name, description, weight], i) =>
        env.DB.prepare(
          `INSERT INTO eval_criteria (cycle_id, target_type, name, description, weight, sort_order, is_active)
           SELECT NULL, 'students', ?, ?, ?, ?, 1 WHERE ${pending}`,
        ).bind(name, description, weight, i)),
      env.DB.prepare(`UPDATE settings SET criteria_seed = ? WHERE id = 1`).bind(SEED_MARK),
    ]);
  } catch (e) {
    console.error('student criteria seed failed', e);
  }
}
